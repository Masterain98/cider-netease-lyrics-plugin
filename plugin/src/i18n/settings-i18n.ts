export const settingsMessages: Record<ResolvedLocale, Catalog> = {
  "zh-CN": zhCN,
  "zh-TW": zhTW,
  "en-US": enUS,
};

export function normalizeLocale(locale?: string | null): ResolvedLocale {
  const normalized = locale?.trim().replaceAll("_", "-").toLowerCase();
  if (normalized?.startsWith("zh")) {
    return normalized.includes("tw") || normalized.includes("hk") || normalized.includes("hant") ? "zh-TW" : "zh-CN";
  }
  return "en-US";
}

export function readCiderLanguage(): string {
  try {
    const cider = (window as typeof window & { CiderApp?: { config?: { getRef?: () => unknown } } }).CiderApp;
    const config = cider?.config?.getRef?.() as { value?: unknown; general?: { language?: string } } | undefined;
    const configValue = (config?.value ?? config) as { general?: { language?: string } } | undefined;
    if (configValue?.general?.language) return configValue.general.language;
  } catch {
    // Preview and test environments do not expose the host config.
  }
  return document.documentElement.lang || navigator.language || "en-US";
}

export function resolveLocale(preference: SettingsLocale, hostLanguage = readCiderLanguage()): ResolvedLocale {
  return preference === "auto" ? normalizeLocale(hostLanguage) : preference;
}

export function translate(locale: ResolvedLocale, key: MessageKey, variables: Record<string, string | number> = {}): string {
  return Object.entries(variables).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    settingsMessages[locale][key],
  );
}

